const FALLBACK = '🛒';

/** The emoji for an Ingredient, or a basket for free-text items with no Ingredient. */
export function ingredientEmoji(ingredient?: { name: string; category: string } | null): string {
  if (!ingredient) return FALLBACK;
  return INGREDIENT_EMOJI[ingredient.name] ?? CATEGORY_EMOJI[ingredient.category] ?? FALLBACK;
}

